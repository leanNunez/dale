def test_alembic_check_covers_the_demo_schema(engines: dict[str, Engine]) -> None:
    """A demo column the metadata lacks is drift: CI's `alembic check` would fail on it."""
    owner = engines["dale_owner"]
    with owner.begin() as conn:
        conn.exec_driver_sql("ALTER TABLE demo.counter ADD COLUMN drift integer")
    try:
        with pytest.raises(AutogenerateDiffsDetected, match="drift"):
            command.check(alembic_config())
    finally:
        with owner.begin() as conn:
            conn.exec_driver_sql("ALTER TABLE demo.counter DROP COLUMN drift")
    command.check(alembic_config())


def test_the_reseed_leaves_every_demo_table_unchanged(
    engines: dict[str, Engine], app: Engine
) -> None:
    """O11 and S11.6: the control row, the ledger, the counters and the transcripts survive."""
    owner = engines["dale_owner"]
    with owner.begin() as conn:
        for table, row in ROWS.items():
            conn.execute(sa.insert(table), row)
    try:
        before = _snapshot(owner, demo.METADATA)
        assert all(before.values())
        reseed(app)
        assert _snapshot(owner, demo.METADATA) == before
    finally:
        with owner.begin() as conn:
            for table in reversed(demo.METADATA.sorted_tables):
                if table is not demo.control:
                    conn.execute(sa.delete(table))


