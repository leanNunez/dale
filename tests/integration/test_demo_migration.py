def test_a_v02_database_with_data_upgrades_and_keeps_it(step_database: Config) -> None:
    """0006 only adds: the erp and brain rows of a 0005 database are untouched by the upgrade."""
    engine = sa.create_engine(step_database.attributes["url"])
    key = {"company_id": el_hornero.COMPANY_ID, "id": REF}
    try:
        reseed(engine)
        with engine.begin() as conn:
            for table, row in BRAIN_ROWS.items():
                conn.execute(sa.insert(table), key | row)
        before = _snapshot(engine, erp.METADATA, brain.METADATA)
        assert all(before[t.fullname] for t in BRAIN_ROWS)
        command.upgrade(step_database, "head")
        assert _snapshot(engine, erp.METADATA, brain.METADATA) == before
        with engine.connect() as conn:
            assert conn.execute(sa.select(demo.control.c.reason)).scalars().all() == ["initial"]
    finally:
        engine.dispose()
