def _snapshot(engine: Engine, *metadata: sa.MetaData) -> dict[str, list[Any]]:
    with engine.connect() as conn:
        return {
            t.fullname: sorted(tuple(r) for r in conn.execute(sa.select(t)))
            for m in metadata
            for t in m.sorted_tables
        }


def test_upgrade_head_creates_every_demo_table(engines: dict[str, Engine]) -> None:
    with engines["dale_owner"].connect() as conn:
        found = conn.execute(
            text("SELECT tablename FROM pg_tables WHERE schemaname = 'demo'")
        ).scalars()
        assert set(found) == {t.name for t in demo.METADATA.sorted_tables}


