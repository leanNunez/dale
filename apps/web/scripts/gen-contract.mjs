// Generates the page's contract types from the host's published schemas (D20, S5.3):
//   npm run gen:contract
// Reads contracts/v1/*.schema.json and components.json, writes src/contract/generated/ (committed).
// The output is deterministic, so CI regenerates it and fails on any `git diff`.
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const SOURCE = resolve(here, "../../../contracts/v1");
// GEN_CONTRACT_OUT lets the drift test regenerate into a scratch folder.
const OUT = process.env.GEN_CONTRACT_OUT ?? resolve(here, "../src/contract/generated");
const BANNER =
  "// Generated by `npm run gen:contract` from contracts/v1. Do not edit: change the Python types.";

async function schemaFiles() {
  const names = await readdir(SOURCE);
  return names.filter((name) => name.endsWith(".schema.json")).sort();
}

async function typesFor(file) {
  const schema = JSON.parse(await readFile(join(SOURCE, file), "utf8"));
  const name = file.replace(/\.schema\.json$/, "");
  const source = await compile(schema, name, {
    additionalProperties: false,
    bannerComment: BANNER,
    cwd: SOURCE,
    format: true,
    strictIndexSignatures: true,
    unknownAny: true,
  });
  return [`${name}.ts`, source];
}

async function componentsMap() {
  const map = JSON.parse(await readFile(join(SOURCE, "components.json"), "utf8"));
  const body = JSON.stringify(map, null, 2);
  return [
    "components.ts",
    `${BANNER}\n\n` +
      `/** Event type to the one component that renders it; the page switches over it. */\n` +
      `export const COMPONENTS = ${body} as const;\n\n` +
      `export type EventType = keyof typeof COMPONENTS;\n` +
      `export type ComponentName = (typeof COMPONENTS)[EventType];\n`,
  ];
}

const files = [...(await Promise.all((await schemaFiles()).map(typesFor))), await componentsMap()];
await rm(OUT, { recursive: true, force: true });
await mkdir(OUT, { recursive: true });
for (const [name, text] of files) {
  await writeFile(join(OUT, name), text);
}
console.log(`wrote ${files.length} files to src/contract/generated`);
