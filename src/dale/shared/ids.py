"""Typed identifiers and the injectable UUID generator."""

from itertools import count
from typing import NewType, Protocol
from uuid import UUID, uuid4

CompanyId = NewType("CompanyId", UUID)
CustomerId = NewType("CustomerId", UUID)
ProductId = NewType("ProductId", UUID)
ProposalId = NewType("ProposalId", UUID)
OrderId = NewType("OrderId", UUID)


class IdGenerator(Protocol):
    def new_id(self) -> UUID: ...


class Uuid4Generator:
    def new_id(self) -> UUID:
        return uuid4()


class SequentialIdGenerator:
    """Deterministic ids (version 4 shape) for tests and evals."""

    def __init__(self) -> None:
        self._counter = count(1)

    def new_id(self) -> UUID:
        return UUID(int=next(self._counter), version=4)


_DEFAULT_GENERATOR = Uuid4Generator()


def new_proposal_id(ids: IdGenerator = _DEFAULT_GENERATOR) -> ProposalId:
    """Proposal ids are generated by code, never by the model."""
    return ProposalId(ids.new_id())
