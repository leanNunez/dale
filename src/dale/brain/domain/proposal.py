"""A prepared order owned by the brain (R3, D6). It is never a confirmed order by itself."""

from dataclasses import dataclass
from datetime import date, datetime
from enum import StrEnum
from typing import Self

from dale.brain.domain.session import SessionContext
from dale.shared.ids import ConversationId, CustomerId, ProductId, ProposalId
from dale.shared.money import Money, money_sum


class ProposalStatus(StrEnum):
    PREPARED = "prepared"
    SUPERSEDED = "superseded"
    CONFIRMED = "confirmed"
    REJECTED = "rejected"


@dataclass(frozen=True, slots=True)
class ProposalLine:
    product_id: ProductId
    name: str  # management's catalog name from the quote, never from the model (B61)
    quantity: int
    unit_price: Money  # frozen from erp_sim.quote; no tool input carries a price
    line_total: Money


@dataclass(frozen=True, slots=True)
class OrderProposal:
    id: ProposalId  # generated by code, never by the model
    conversation_id: ConversationId
    customer_id: CustomerId
    status: ProposalStatus
    lines: tuple[ProposalLine, ...]
    total: Money
    delivery_date: date
    created_at: datetime

    def __post_init__(self) -> None:
        if not self.lines:
            raise ValueError("a proposal has at least one line")
        if any(x.line_total != x.unit_price * x.quantity for x in self.lines):
            raise ValueError("a line total is its quantity times its unit price")
        if self.total != money_sum(x.line_total for x in self.lines):
            raise ValueError("a proposal total is the sum of its lines")

    @classmethod
    def prepared(
        cls,
        id: ProposalId,
        session: SessionContext,
        quoted: tuple[ProposalLine, ...],
        total: Money,
        delivery_date: date,
        quoted_at: datetime,
    ) -> Self:
        """A new proposal for the session's own conversation and customer."""
        status = ProposalStatus.PREPARED
        who = (session.conversation_id, session.customer_id)
        return cls(id, *who, status, quoted, total, delivery_date, quoted_at)
